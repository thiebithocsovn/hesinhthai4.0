import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { collection,doc,getDoc,getDocs,query,setDoc,updateDoc,deleteDoc,serverTimestamp,where } from 'firebase/firestore';
import { prepareAssignment,assignmentId,type StaffExam } from '../src/lib/examStaffAccess';
if(!process.env.FIRESTORE_EMULATOR_HOST)throw new Error('Emulator only');
const [host,port]=process.env.FIRESTORE_EMULATOR_HOST.split(':');
const env=await initializeTestEnvironment({projectId:'demo-learning-wall',firestore:{host,port:Number(port),rules:readFileSync('firestore.rules','utf8')}});
const revision='2026-11-24T08:00:00.000Z';
const exam:StaffExam={id:'exam-a',title:'Kiểm tra Toán',teacherId:'owner',status:'draft',councilPlan:{version:1,name:'Hội đồng A',schoolName:'Trường A',site:'Điểm 1',updatedAt:revision,members:[{id:'m1',name:'Giám thị A',role:'Giám thị',room:'Phòng 01',teacherUid:'proctor'},{id:'m2',name:'Chấm A',role:'Cán bộ chấm thi',room:'',teacherUid:'grader'},{id:'m3',name:'Ngoài trường',role:'Thư ký',room:'',teacherUid:'outside'},{id:'m4',name:'Inactive',role:'Hỗ trợ',room:'',teacherUid:'inactive'}]}};
try{
  await env.clearFirestore();
  await env.withSecurityRulesDisabled(async ctx=>{
    const db=ctx.firestore();
    for(const [id,school,status] of [['owner','Trường A','active'],['proctor','Trường A','active'],['grader','Trường A','active'],['outside','Trường B','active'],['inactive','Trường A','inactive'],['unrelated','Trường A','active']])await setDoc(doc(db,'teachers',id),{id,school,status});
    await setDoc(doc(db,'exams',exam.id),{...exam,questions:[{id:'q1',correctAnswer:1}]});
    await setDoc(doc(db,'results','r1'),{teacherId:'owner',examId:exam.id,score:9,answers:{q1:1}});
    await setDoc(doc(db,'exam_sessions','s1'),{teacherId:'owner',examId:exam.id,draftAnswers:{q1:1}});
    await setDoc(doc(db,'students','s1'),{teacherId:'owner',name:'Student'});
  });
  const owner=env.authenticatedContext('owner').firestore(),proctor=env.authenticatedContext('proctor').firestore(),grader=env.authenticatedContext('grader').firestore(),outside=env.authenticatedContext('outside').firestore(),inactive=env.authenticatedContext('inactive').firestore(),unrelated=env.authenticatedContext('unrelated').firestore(),guest=env.unauthenticatedContext().firestore();
  const admin=env.authenticatedContext('administrator',{admin:true}).firestore();
  const path=(uid:string,rev=revision)=>'exam_staff_assignments/'+assignmentId(exam.id,uid,rev);
  const grant=(index:number,issuer='owner')=>({...prepareAssignment(exam,index,issuer),grantedAt:serverTimestamp(),updatedAt:serverTimestamp()});
  await assertFails(setDoc(doc(proctor,path('proctor')),grant(0,'proctor')));
  await assertFails(setDoc(doc(outside,path('proctor')),grant(0,'outside')));
  await assertFails(setDoc(doc(owner,path('proctor')),{...grant(0),role:'Chủ tịch',kind:'decision'}));
  await assertFails(setDoc(doc(owner,path('proctor')),{...grant(0),room:'Phòng 02'}));
  await assertFails(setDoc(doc(owner,path('proctor')),{...grant(0),kind:'grading_report'}));
  await assertFails(setDoc(doc(owner,path('outside')),grant(2)));
  await assertFails(setDoc(doc(admin,path('outside')),grant(2,'administrator')));
  await assertFails(setDoc(doc(owner,path('inactive')),grant(3)));
  await assertSucceeds(setDoc(doc(owner,path('proctor')),grant(0)));
  await assertSucceeds(setDoc(doc(admin,path('grader')),grant(1,'administrator')));
  await assertSucceeds(getDoc(doc(proctor,path('proctor'))));
  await assertSucceeds(getDocs(query(collection(proctor,'exam_staff_assignments'),where('staffUid','==','proctor'))));
  await assertSucceeds(getDocs(query(collection(owner,'exam_staff_assignments'),where('teacherId','==','owner'),where('examId','==',exam.id))));
  await assertFails(getDocs(collection(proctor,'exam_staff_assignments')));
  await assertFails(getDoc(doc(proctor,path('grader'))));
  await assertFails(getDoc(doc(unrelated,path('proctor'))));
  await assertFails(getDoc(doc(guest,path('proctor'))));
  await assertFails(getDoc(doc(proctor,'exams',exam.id)));
  await assertFails(getDoc(doc(proctor,'exam_sessions','s1')));
  await assertFails(getDoc(doc(grader,'results','r1')));
  await assertFails(updateDoc(doc(grader,'results','r1'),{score:10}));
  await assertFails(getDoc(doc(proctor,'students','s1')));
  await assertFails(updateDoc(doc(proctor,path('proctor')),{role:'Chủ tịch',state:'ready',updatedAt:serverTimestamp()}));
  await assertFails(updateDoc(doc(proctor,path('proctor')),{state:'issue',report:'',updatedAt:serverTimestamp()}));
  await assertFails(updateDoc(doc(proctor,path('proctor')),{state:'ready',report:'ok',updatedAt:new Date(0)}));
  await assertFails(updateDoc(doc(owner,path('proctor')),{state:'completed',report:'forged',updatedAt:serverTimestamp()}));
  await assertSucceeds(updateDoc(doc(proctor,path('proctor')),{state:'issue',report:'Máy cần kiểm tra',updatedAt:serverTimestamp()}));
  await assertFails(updateDoc(doc(proctor,path('proctor')),{active:false,revokedBy:'proctor',revokedAt:serverTimestamp(),updatedAt:serverTimestamp()}));
  await assertSucceeds(updateDoc(doc(owner,path('proctor')),{active:false,revokedBy:'owner',revokedAt:serverTimestamp(),updatedAt:serverTimestamp()}));
  const revoked=(await assertSucceeds(getDoc(doc(owner,path('proctor'))))).data()!;
  assert.equal(revoked.active,false);assert.equal(revoked.report,'Máy cần kiểm tra');
  await assertFails(updateDoc(doc(proctor,path('proctor')),{state:'completed',report:'cannot',updatedAt:serverTimestamp()}));
  await assertFails(deleteDoc(doc(owner,path('proctor'))));
  await assertFails(setDoc(doc(owner,path('proctor')),grant(0)));
  // Change the council version: the old authorization cannot write even when active.
  await assertSucceeds(updateDoc(doc(owner,'exams',exam.id),{'councilPlan.updatedAt':'2026-11-24T09:00:00.000Z'}));
  await assertFails(updateDoc(doc(grader,path('grader')),{state:'ready',report:'old version',updatedAt:serverTimestamp()}));
  const newExam={...exam,councilPlan:{...exam.councilPlan!,updatedAt:'2026-11-24T09:00:00.000Z'}};
  const newId=path('grader',newExam.councilPlan.updatedAt);
  await assertSucceeds(setDoc(doc(owner,newId),{...prepareAssignment(newExam,1,'owner'),grantedAt:serverTimestamp(),updatedAt:serverTimestamp()}));
  await assertSucceeds(updateDoc(doc(grader,newId),{state:'ready',report:'new version',updatedAt:serverTimestamp()}));
  await assertSucceeds(updateDoc(doc(owner,'exams',exam.id),{status:'closed'}));
  await assertFails(updateDoc(doc(grader,newId),{state:'completed',report:'closed',updatedAt:serverTimestamp()}));
  await assertFails(getDoc(doc(inactive,path('grader'))));
  console.log('Staff RBAC emulator: ownership, role/room binding, same-school active accounts, no private exam/results/session access, timestamps, revocation, revision and close checks passed.');
}finally{await env.cleanup();}
