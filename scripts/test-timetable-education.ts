import assert from 'node:assert/strict';
import { activeTimetableDays, analyzeTimetableScenario, createDefaultTimetableScenario, normalizeTimetableScenario, optimizeTimetable, type TimetableScenario, type TimetableSolution } from '../src/lib/smartTimetable';
import { applyEducationConfiguration, createEducationConfiguration, EDUCATION_PROFILES, educationScenarioIssues, entryClockLabel, inferEducationKind, scenarioForTeachingWeek } from '../src/lib/timetableEducation';
import { auditTimetableSolution } from '../src/lib/smartTimetableAudit';
import { parseImportedSlots, scenarioFromAssignmentRows } from '../src/lib/smartTimetableImport';
import { createTimetableWorkbook } from '../src/lib/timetableExcel';
import { makePublicTimetable, publicTimetableHtml, validatePublicTimetable } from '../src/lib/timetablePublication';
import { timetablePrintHtml } from '../src/lib/timetablePrint';
import { mergeTimetableAssignments } from '../src/lib/timetableGrouping';
import * as XLSX from 'xlsx';

const empty: TimetableScenario = { name: 'Trường kiểm thử cấp học', periodsPerDay: 7, teachers: [], classes: [], subjects: [], rooms: [], assignments: [] };
const sample = createDefaultTimetableScenario();
assert.equal(inferEducationKind(sample), 'primary-lower');
assert.equal(normalizeTimetableScenario(sample).education, undefined, 'Legacy JSON keeps ordinal time semantics until explicitly migrated.');
assert.throws(() => applyEducationConfiguration(sample, createEducationConfiguration('university')), /không chứa/);
assert.ok(sample.assignments.length > 0);

for (const profile of EDUCATION_PROFILES) {
  const s = applyEducationConfiguration(empty, createEducationConfiguration(profile.id));
  const level = s.education!.levels[0];
  s.classes = [{ id: 'c', name: 'Lớp thử', level }];
  s.teachers = [{ id: 't', name: 'Giáo viên thử', level }];
  s.subjects = [{ id: 'm', name: 'Môn thử' }];
  s.assignments = [{ id: 'a', classId: 'c', subjectId: 'm', teacherId: 't', periodsPerWeek: 2, blockSize: 2, maxPerDay: 2 }];
  assert.deepEqual(educationScenarioIssues(s), [], profile.name);
  const result = optimizeTimetable(s, [], 20), audit = auditTimetableSolution(s, result);
  assert.ok(audit.valid && audit.complete, profile.name + ': ' + audit.errors.join('; '));
  assert.match(entryClockLabel(s, result.entries[0]), /^\d{2}:\d{2}–\d{2}:\d{2}$/);
}

const mixed = applyEducationConfiguration(empty, createEducationConfiguration('primary-lower'));
mixed.classes = [{ id: 'p', name: '5A', level: 'Tiểu học' }, { id: 's', name: '6A', level: 'THCS' }];
mixed.teachers = [{ id: 't', name: 'Giáo viên liên cấp', level: 'Liên cấp' }];
mixed.subjects = [{ id: 'm', name: 'Tin học' }]; mixed.rooms = [{ id: 'r', name: 'Phòng chung' }];
mixed.assignments = [{ id: 'a', classId: 'p', subjectId: 'm', teacherId: 't', roomId: 'r', periodsPerWeek: 1, maxPerDay: 1, fixedStartSlots: ['0:3'] }, { id: 'b', classId: 's', subjectId: 'm', teacherId: 't', roomId: 'r', periodsPerWeek: 1, maxPerDay: 1, fixedStartSlots: ['0:2'] }];
const collision = optimizeTimetable(mixed, [], 20);
assert.ok(collision.entries.length < 2, 'Different period indices overlap on real clocks and cannot both be placed.');
const forged: TimetableSolution = { ...collision, teachingWeek: 1, entries: mixed.assignments.map((a, i) => ({ id: a.id, assignmentId: a.id, classId: a.classId, subjectId: a.subjectId, teacherId: a.teacherId, roomId: a.roomId, dayIndex: 0, period: i ? 2 : 3 })) };
assert.ok(auditTimetableSolution(mixed, forged).errors.some(e => e.includes('Trùng giáo viên')));
assert.ok(auditTimetableSolution(mixed, forged).errors.some(e => e.includes('Trùng phòng')));

const disjoint = structuredClone(mixed);
disjoint.education!.timings[1].morningStart = '08:00';
disjoint.assignments.forEach(a => a.fixedStartSlots = ['0:1']);
const correct = optimizeTimetable(disjoint, [], 20);
assert.equal(correct.entries.length, 2, 'Same ordinal at disjoint clocks is allowed for a shared teacher/room.');
assert.ok(auditTimetableSolution(disjoint, correct).valid);

const travel = structuredClone(disjoint);
travel.campuses = [{ id: 'north', name: 'Điểm Bắc' }, { id: 'south', name: 'Điểm Nam' }];
travel.assignments[0].campusId = 'north'; travel.assignments[1].campusId = 'south';
travel.campusTravelMinutes = 30;
assert.ok(optimizeTimetable(travel, [], 20).entries.length < 2, 'A 25 minute gap cannot satisfy a declared 30 minute transfer.');
const forgedTravel = { ...correct, entries: correct.entries.map(e => ({ ...e, campusId: travel.assignments.find(a => a.id === e.assignmentId)!.campusId })) };
assert.ok(auditTimetableSolution(travel, forgedTravel).errors.some(e => e.includes('chuyển cơ sở')));
travel.campusTravelMinutes = 25;
assert.ok(auditTimetableSolution(travel, optimizeTimetable(travel, [], 20)).valid);
const parallel = structuredClone(mixed);
parallel.teachers.push({ id: 't2', name: 'Giáo viên 2', level: 'THCS' });
parallel.assignments[1].teacherId = 't2';
parallel.assignments.forEach(a => { a.fixedStartSlots = ['0:1']; a.roomId = undefined; });
parallel.lessonGroups = [{ id: 'parallel', name: 'Song song liên cấp', kind: 'parallel', assignmentIds: ['a','b'] }];
assert.ok(optimizeTimetable(parallel, [], 20).entries.length < 2, 'Parallel lessons require equal real intervals across levels.');
const consecutive = structuredClone(disjoint);
consecutive.classes[1].level = 'Tiểu học';
consecutive.assignments[1].fixedStartSlots = ['0:2'];
consecutive.teachers[0].maxConsecutivePeriods = 1;
assert.ok(optimizeTimetable(consecutive, [], 20).entries.length < 2, 'Consecutive teaching limits follow real lesson endings and breaks.');
const noCalendar = structuredClone(empty);
noCalendar.assignments = [{ id: 'a', classId: 'x', subjectId: 'x', teacherId: 'x', periodsPerWeek: 1, weekPattern: 'odd' }];
assert.ok(analyzeTimetableScenario(noCalendar).some(e => e.includes('khai báo học kỳ')));

const uni = applyEducationConfiguration(empty, createEducationConfiguration('university'));
uni.daysPerWeek = 7;
uni.classes = [{ id: 'u', name: 'CNTT K26', level: 'Đại học', programme: 'CNTT', cohort: 'K26' }];
uni.teachers = [{ id: 't', name: 'Giảng viên', level: 'Đại học' }];
uni.subjects = [{ id: 'm', name: 'Lập trình', code: 'IT101', credits: 3 }];
uni.assignments = [{ id: 'odd', classId: 'u', teacherId: 't', subjectId: 'm', courseSectionCode: 'IT101-01', periodsPerWeek: 2, blockSize: 2, maxPerDay: 2, session: 'evening', fixedStartSlots: ['6:11'], startWeek: 1, endWeek: 15, weekPattern: 'odd' }, { id: 'even', classId: 'u', teacherId: 't', subjectId: 'm', periodsPerWeek: 1, startWeek: 2, endWeek: 10, weekPattern: 'even' }];
assert.equal(activeTimetableDays(uni).at(-1), 'Chủ Nhật');
assert.deepEqual(parseImportedSlots('CN-11;6:15'), ['6:11', '6:15']);
assert.deepEqual(scenarioForTeachingWeek(uni).assignments.map(a => a.id), ['odd']);
const week1 = optimizeTimetable(uni, [], 20);
assert.equal(week1.teachingWeek, 1); assert.equal(week1.entries.length, 2);
assert.ok(week1.entries.every(e => e.dayIndex === 6 && e.period >= 11));
assert.ok(auditTimetableSolution(uni, week1).valid);
const week2 = structuredClone(uni); week2.education!.activeWeek = 2;
assert.deepEqual(scenarioForTeachingWeek(week2).assignments.map(a => a.id), ['even']);
assert.ok(!auditTimetableSolution(week2, week1).valid, 'An old week cannot be restored or published as the current week.');
assert.equal(optimizeTimetable(week2, [], 20).entries.length, 1);
const invalidWeek = structuredClone(uni); invalidWeek.assignments[1].endWeek = 40;
assert.ok(analyzeTimetableScenario(invalidWeek).some(e => e.includes('Khoảng tuần')));
assert.ok(optimizeTimetable(invalidWeek, [], 20).diagnostics.hardConflicts.length);

const options = { title: 'Lịch học kỳ', notes: '', effectiveFrom: '', effectiveTo: '', showTeacherNames: false };
const snapshot = makePublicTimetable(uni, week1, options);
assert.ok(validatePublicTimetable(snapshot)); assert.equal(snapshot.days, 7);
assert.equal(snapshot.entries[0].clockLabel, '18:00–18:50');
assert.match(snapshot.academicLabel!, /Tuần 1/);
assert.ok(publicTimetableHtml(snapshot).includes('Chủ nhật'));
const printed = timetablePrintHtml(uni, week1, 'class', 'u');
assert.ok(printed.includes('18:00–18:50') && printed.includes('Tuần 1'));
const book = createTimetableWorkbook(uni, week1);
assert.ok(XLSX.utils.sheet_to_csv(book.Sheets['Tong hop']).includes('Tuần học,1'));
const restored = scenarioFromAssignmentRows(XLSX.utils.sheet_to_json(book.Sheets['Phan cong']), uni);
assert.equal(restored.classes[0].level, 'Đại học'); assert.equal(restored.subjects[0].credits, 3);
assert.equal(restored.assignments[0].weekPattern, 'odd'); assert.equal(restored.assignments[0].courseSectionCode, 'IT101-01');
const thpt = scenarioFromAssignmentRows([{ 'Lớp': '10A', 'Môn': 'Toán', 'Giáo viên': 'A' }]);
assert.equal(thpt.classes[0].level, 'THPT', 'Grade 10 must never be classified as THCS.');
assert.throws(() => scenarioFromAssignmentRows([{ 'Cấp': 'khác', 'Lớp': '10A', 'Môn': 'Toán', 'Giáo viên': 'A' }]), /không nhận diện/);
const withDifferentWeeks = structuredClone(disjoint); withDifferentWeeks.assignments[1].startWeek = 2;
assert.throws(() => mergeTimetableAssignments(withDifferentWeeks, ['a', 'b'], 'r'), /khoảng tuần/);
console.log('Education profiles: ten types, safe migration, real clock collisions, evening/Sunday, semester weeks, independent audit, import and export passed.');
