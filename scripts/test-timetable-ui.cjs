    await nav('Điều động dạy thay').click();
    await page.getByRole('heading', { name: 'Điều động giáo viên dạy thay' }).waitFor();
    await button('Kiểm tra và lưu dạy thay').click();
    await page.getByText('Cần một thời khóa biểu đã được kiểm tra độc lập và một tiết được chọn.').waitFor();
    await nav('Phân tích PCCM').click();
    const diagnosticEvent = page.waitForEvent('download');
    await button('Tải báo cáo kiểm tra Excel').click();
    const diagnosticFile = await diagnosticEvent, diagnosticBook = XLSX.readFile(await diagnosticFile.path());
