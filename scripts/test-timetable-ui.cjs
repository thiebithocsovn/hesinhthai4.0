const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const XLSX = require('xlsx');
(async () => {
  const { createServer } = await import('vite');
  const vite = await createServer({ server: { host: '127.0.0.1', port: 3298, strictPort: true, hmr: false } });
  await vite.listen(); let browser;
  fs.mkdirSync('timetable-ui-results', { recursive: true });
  try {
    browser = await chromium.launch({ headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 950 } });
    const page = await context.newPage(), errors = []; page.on('pageerror', e => errors.push(e.message)); page.setDefaultTimeout(18000);
    await page.goto('http://127.0.0.1:3298/hesinhthai4.0/scripts/fixtures/timetable-preview.html');
    const nav = name => page.getByRole('navigation', { name: 'Chức năng thời khóa biểu' }).getByRole('button', { name, exact: true });
    const button = name => page.getByRole('button', { name, exact: true });
    const workspace = () => page.evaluate(() => JSON.parse(localStorage.getItem('qa-aitherova-timetable-complete')));
    await nav('Ghép lớp').click();
    await page.getByRole('checkbox', { name: /6A · Toán · Thầy Toán/ }).check();
    await page.getByRole('checkbox', { name: /6B · Toán · Thầy Toán/ }).check();
    await page.getByLabel('Phòng cho lớp ghép').selectOption('r1');
    await button('Xem trước ghép lớp').click();
    assert.equal((await workspace()).scenario.assignments.length, 4, 'Preview does not mutate the workspace.');
    await button('Áp dụng ghép lớp').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('qa-aitherova-timetable-complete')).scenario.assignments.length === 3);
    await button('Xếp tự động').click();
    await page.getByText('Đã kiểm tra độc lập: đủ tiết, không trùng lớp, giáo viên hoặc phòng.', { exact: true }).waitFor();
    await page.getByLabel('Chọn đối tượng xem lịch').selectOption('6b');
    assert.ok((await page.getByRole('main').innerText()).includes('Toán'), 'Merged math appears in the second class.');
    const excelEvent = page.waitForEvent('download'); await button('Xuất Excel').click();
    const excel = await excelEvent, book = XLSX.readFile(await excel.path());
    assert.ok(XLSX.utils.sheet_to_csv(book.Sheets['Lop 6B']).includes('Toán'));
    await nav('Liên kết tra cứu').click();
    assert.equal(await button('Công bố và tạo liên kết').isDisabled(), true, 'Publishing needs explicit review.');
    const htmlEvent = page.waitForEvent('download'); await button('Xem trước / Tải trang HTML').click();
    const exported = await htmlEvent, html = fs.readFileSync(await exported.path(), 'utf8');
    assert.ok(html.includes('application/json')); assert.ok(!html.includes('unavailableSlots')); assert.ok(!html.includes('Thầy Toán'));
    await button('Hoàn tác thay đổi').click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('qa-aitherova-timetable-complete')).scenario.assignments.length === 4);
    await nav('Tách lớp').click(); await button('Tạo nhóm học').click();
    await page.getByRole('combobox', { name: 'Nhóm học 6A · Toán · Thầy Toán · 2 tiết', exact: true }).selectOption({ label: 'Nhóm 1' });
    await page.getByRole('combobox', { name: 'Nhóm học 6A · Tiếng Anh · Cô Anh · 2 tiết', exact: true }).selectOption({ label: 'Nhóm 2' });
    await nav('Khối - môn - số tiết').click(); await page.getByLabel('Phòng 6A Tiếng Anh', { exact: true }).selectOption('r2');
    await nav('Tách lớp').click();
    await page.getByRole('checkbox', { name: /6A · Toán · Thầy Toán/ }).check();
    await page.getByRole('checkbox', { name: /6A · Tiếng Anh · Cô Anh/ }).check();
    await page.getByLabel('Tên nhóm ràng buộc').fill('Thực hành song song 6A'); await button('Lưu nhóm ràng buộc').click();
    await button('Xếp tự động').click(); await page.getByText('Đã kiểm tra độc lập: đủ tiết, không trùng lớp, giáo viên hoặc phòng.', { exact: true }).waitFor();
    await page.getByLabel('Chọn đối tượng xem lịch').selectOption('6a');
    assert.equal(await page.getByText('Nhóm 1', { exact: true }).count(), 2);
    assert.equal(await page.getByText('Nhóm 2', { exact: true }).count(), 2);
    const data = await workspace(); const grouped = data.solution.entries.filter(e => e.classId === '6a');
    assert.equal(new Set(grouped.map(e => `${e.dayIndex}:${e.period}`)).size, 2, 'Both student groups share the same two clock slots.');
    await nav('Bảng lịch toàn trường').click(); await page.screenshot({ path: 'timetable-ui-results/school-board-desktop.png', fullPage: true });
    assert.ok((await page.getByRole('main').innerText()).includes('6B'));
    await page.setViewportSize({ width: 390, height: 844 });
    await button('Mở menu thời khóa biểu').click(); await nav('Cơ sở trường học').click();
    await page.getByRole('heading', { name: 'Cơ sở trường học', exact: true }).first().waitFor();
    assert.equal(await button('Mở menu thời khóa biểu').getAttribute('aria-expanded'), 'false');
    await page.screenshot({ path: 'timetable-ui-results/campus-mobile.png', fullPage: true });
    const overflow = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth, elements: [...document.querySelectorAll('main *')].map(el => ({ tag: el.tagName, className: el.className, left: Math.round(el.getBoundingClientRect().left), right: Math.round(el.getBoundingClientRect().right), text: (el.textContent || '').slice(0, 60) })).filter(el => el.right > document.documentElement.clientWidth + 1 && el.left >= 0).slice(0, 20) }));
    assert.ok(overflow.scroll <= overflow.width + 1, 'Mobile page has no horizontal document overflow: ' + JSON.stringify(overflow));
    assert.deepEqual(errors, []);
    console.log('Timetable UI: preview/merge, safe scheduling, Excel/HTML exports, undo, parallel subgroups, school board and mobile navigation passed.');
  } finally { if (browser) await browser.close(); await vite.close(); }
})().catch(error => { console.error(error); process.exit(1); });
