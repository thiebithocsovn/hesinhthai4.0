    assert.equal(await page.getByRole('heading', { name: 'Chưa có phân công giảng dạy' }).count(), 0, 'Hide empty state after assignment is added.');
    await nav('Khối - môn - số tiết').click();
    await page.getByLabel('Mã lớp học phần CNTT K26 Lập trình').fill('IT101-01');
