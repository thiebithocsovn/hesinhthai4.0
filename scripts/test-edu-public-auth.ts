import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (path: string) => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const app = read('src/App.tsx');
const bootstrap = read('src/components/PlatformBootstrap.tsx');
const publicPage = read('src/components/EduPublicLanding.tsx');
const desktop = read('src/components/FastLandingPage.tsx');
assert.ok(bootstrap.includes('<EduPublicLanding'));
assert.ok(!bootstrap.includes('<FastLandingPage'));
assert.ok(app.includes("if (!currentUser || !auth.currentUser) return <EduPublicLanding"));
assert.ok(app.indexOf("if (!currentUser || !auth.currentUser) return <EduPublicLanding") < app.indexOf('return <FastLandingPage'));
assert.ok(app.includes('<EduPublicLanding authMode={authMode}'));
assert.ok(app.includes('onSubmit={handleLogin}'));
assert.ok(app.includes('onSubmit={handleRegister}'));
assert.ok(app.includes('handleGoogleSignIn()'));
assert.ok(app.includes("if (currentView === 'student_exam')"));
assert.ok(app.includes("new URLSearchParams(window.location.search).get('auth') === 'register'"));
assert.ok(publicPage.includes('id="bang-gia"'));
assert.ok(publicPage.includes('499.000đ'));
assert.ok(publicPage.includes('Học sinh tham gia kỳ thi'));
assert.ok(!desktop.includes('id="bang-gia"'));
assert.ok(!desktop.includes('499.000đ'));
assert.ok(!desktop.includes('Gói dịch vụ và bảng giá'));
assert.ok(desktop.includes('aria-label="Start Menu Edu AI"'));
assert.ok(desktop.includes('<EduAgentDock'));
assert.ok(desktop.includes('<EduWindowLayer'));
console.log('Public marketing/auth and private desktop separation: checks passed.');
