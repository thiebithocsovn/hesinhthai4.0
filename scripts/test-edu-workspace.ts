import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { openWindow, isWindowApp, WINDOW_APPS } from '../src/components/EduWorkspace';
import { ECOSYSTEM_APPLICATIONS } from '../src/ecosystem';

assert.equal(WINDOW_APPS.length, 4);
assert.ok(WINDOW_APPS.every(id => ECOSYSTEM_APPLICATIONS.some(app => app.id === id && app.dependency === 'browser')));
for (const restricted of ['learning-wall', 'exam-manager', 'plicker', 'kpi-manager', 'smart-timetable', 'chatbot']) assert.equal(isWindowApp(restricted), false);
const first = openWindow([], 'excel-merger');
assert.equal(first.length, 1);
assert.equal(first[0].layout, 'normal');
assert.ok(first[0].x + first[0].width <= 100);
assert.ok(first[0].y + first[0].height <= 100);
const second = openWindow(first, 'pdf-merger');
assert.deepEqual(second.map(w => w.id), ['excel-merger', 'pdf-merger']);
const minimized = second.map(w => w.id === 'excel-merger' ? { ...w, minimized: true, layout: 'left' as const } : w);
const reopened = openWindow(minimized, 'excel-merger');
assert.deepEqual(reopened.map(w => w.id), ['pdf-merger', 'excel-merger']);
assert.equal(reopened[1].minimized, false);
assert.equal(reopened[1].layout, 'left');
assert.equal(first.length, 1);
const home = readFileSync(new URL('../src/components/FastLandingPage.tsx', import.meta.url), 'utf8');
assert.ok(home.includes('props.account && isWindowApp(id)'));
assert.ok(home.includes('data-edu-pin-mode'));
assert.ok(home.includes('edu-ai-launcher-v2:'));
assert.ok(home.includes('beforeunload'));
const app = readFileSync(new URL('../src/App.tsx', import.meta.url), 'utf8');
assert.ok(app.includes("workspaceKey={currentUser && auth.currentUser ? auth.currentUser.uid : 'guest'}"));
console.log('Edu AI workspace model and launcher safety checks passed.');
