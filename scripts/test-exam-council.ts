import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { groupSchools,validateCouncil,schoolKey,type CouncilPlan } from '../src/lib/examCouncil';
import { stripTeacherOnlyFields } from '../src/lib/examManualGrading';
import { protectExamForAccess,openProtectedExamAccess } from '../src/lib/examPrivacy';
const teachers=[{id:'t1',name:'A',school:' Trường A ',status:'active',level:'THCS'},{id:'t2',name:'B',school:'TRƯỜNG   A',status:'inactive',level:'THCS'},{id:'t3',name:'C',school:'Trường B',status:'active',level:'THPT'}];
const groups=groupSchools(teachers);
assert.equal(groups.length,2);
assert.equal(groups.find(g=>g.key===schoolKey('Trường A'))?.active,1);
const plan:CouncilPlan={version:1,name:'Hội đồng A',schoolName:'Trường A',site:'Điểm A',members:[{id:'a',name:'A',role:'Chủ tịch',room:'',teacherUid:'t1'},{id:'b',name:'B',role:'Thư ký',room:''},{id:'c',name:'C',role:'Giám thị',room:'Phòng 01'}],updatedAt:'2026-11-24'};
assert.deepEqual(validateCouncil(plan,['Phòng 01']),[]);
assert.ok(validateCouncil(plan,[]).length);
assert.ok(validateCouncil({...plan,members:[...plan.members,{id:'a',name:'A',role:'Chủ tịch',room:''}]},['Phòng 01']).length);
assert.ok(validateCouncil({...plan,members:plan.members.filter(m=>m.role!=='Thư ký')},['Phòng 01']).length);
const exam={id:'exam-a',teacherId:'t1',title:'Đề',durationMinutes:45,status:'published' as const,createdAt:'2026-11-24',questions:[{id:'q1',type:'essay',sampleAnswer:'private'}],councilPlan:plan,operationsPlan:{rooms:[]},shuffledVersions:[{code:'version-a',questions:[{id:'q2',type:'essay',sampleAnswer:'private'}]}]};
const cleaned=stripTeacherOnlyFields(exam);
assert.equal('councilPlan' in cleaned,false);
assert.equal('operationsPlan' in cleaned,false);
assert.equal('sampleAnswer' in cleaned.questions[0],false);
assert.equal('sampleAnswer' in cleaned.shuffledVersions[0].questions[0],false);
assert.equal('councilPlan' in exam,true);
const packet=await protectExamForAccess(cleaned,'123456789012');
const opened=await openProtectedExamAccess<typeof cleaned>(packet,'123456789012');
assert.equal('councilPlan' in opened,false);
assert.equal('operationsPlan' in opened,false);
const manager=readFileSync(new URL('../src/components/ExamManagerLegacy.tsx',import.meta.url),'utf8');
const council=readFileSync(new URL('../src/components/TeacherExamCouncil.tsx',import.meta.url),'utf8');
assert.ok(manager.includes('protectExamForAccess(stripTeacherOnlyFields(authorized.exam), authorized.code)'));
assert.ok(manager.includes('<TeacherExamCouncil'));
assert.ok(council.includes("doc(db,'teachers',access.ownerUid)"));
assert.ok(council.includes("access.role==='administrator'"));
assert.ok(council.includes("fresh.status!=='draft'"));
assert.ok(council.includes('tx.update(ref,{councilPlan:plan})'));
console.log('Council: normalized school grouping, role validation, duplicate and room checks, encrypted payload exclusion and draft-only wiring passed.');
