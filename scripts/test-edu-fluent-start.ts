import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { ECOSYSTEM_APPLICATIONS } from '../src/ecosystem';
const home = readFileSync(new URL('../src/components/FastLandingPage.tsx', import.meta.url), 'utf8');
const css = readFileSync(new URL('../src/components/edu-fluent-start.css', import.meta.url), 'utf8');
const pinList = home.match(/const DEFAULT_PINS: LauncherId\[\] = \[([^\]]+)\]/)?.[1] || '';
const ids = [...pinList.matchAll(/'([^']+)'/g)].map(match => match[1]);
assert.equal(ids.length, 15);
assert.equal(new Set(ids).size, 15);
assert.ok(ECOSYSTEM_APPLICATIONS.every(app => ids.includes(app.id)));
assert.ok(ids.includes('smart-timetable'));
assert.ok(home.includes('data-edu-pin-mode'));
assert.ok(home.includes('inert={!start}'));
assert.ok(home.includes('aria-controls="edu-start-menu"'));
assert.ok(home.includes('visibleIds.length===1'));
assert.ok(home.includes('recent.slice(0,3)'));
assert.ok(home.includes('edu-ai:open-agent'));
assert.ok(home.includes('props.account.name'));
assert.ok(!home.includes('499.000đ'));
assert.ok(css.includes('prefers-reduced-motion: reduce'));
assert.ok(css.includes('backdrop-filter: blur(32px)'));
assert.ok(css.includes('cubic-bezier(.2,.8,.2,1)'));
assert.ok(css.includes('repeat(6,minmax(0,1fr))'));
assert.ok(css.includes('repeat(3,minmax(0,1fr))'));
console.log('Fluent Start menu: app coverage, motion, accessible controls and privacy checks passed.');

const desktop = home.slice(home.indexOf('<main aria-label="Màn hình nền Edu AI"'), home.indexOf('</main>',home.indexOf('<main aria-label="Màn hình nền Edu AI"')));
const shortcuts=readFileSync(new URL('../src/components/DesktopShortcuts.tsx',import.meta.url),'utf8');
assert.ok(desktop.includes('<DesktopShortcuts'));
assert.ok(shortcuts.includes('edu-desktop-shortcuts'));
assert.ok(shortcuts.includes('pins.map(id'));
assert.ok(shortcuts.includes('launch(id)'));
assert.ok(!desktop.includes('Xin chào,'));
assert.ok(!desktop.includes('Truy cập nhanh'));
assert.ok(!desktop.includes('Đổi hình nền'));
assert.ok(css.includes('grid-auto-flow:column'));
console.log('Clean desktop shortcut checks passed.');
