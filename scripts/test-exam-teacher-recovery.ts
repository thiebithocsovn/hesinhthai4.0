import assert from 'node:assert/strict';
import {buildTeacherRecovery,encryptTeacherRecovery,readTeacherRecovery} from '../src/lib/examTeacherRecovery';
import {withExamStudentClass} from '../src/lib/examStudentClasses';
import {remainingExamSeconds} from '../src/lib/examResume';
const now=Date.parse('2026-11-24T08:10:00Z');
const exam={id:'exam-a',teacherId:'owner',status:'published',durationMinutes:45,classNames:{a:'4A'},shuffledVersions:[{code:'version-a'}]};
const student={id:'student-a',teacherId:'owner',name:'nguyễn văn an',classId:'a'};
const session={id:'student-a_exam-a',examId:'exam-a',studentId:'student-a',teacherId:'owner',status:'taking',startTime:'2026-11-24T08:00:00Z',examVersion:'version-a',draftAnswers:withExamStudentClass({q1:2},'a')};
const checkpoint=buildTeacherRecovery(exam,student,session,false,now);
assert.equal(checkpoint.student.name,'Nguyễn Văn An');
assert.deepEqual(checkpoint.answers,{q1:2});
assert.equal(checkpoint.examVersion,'version-a');
assert.equal(remainingExamSeconds(checkpoint.startedAt,45,now),35*60);
assert.throws(()=>buildTeacherRecovery(exam,student,session,true,now));
assert.throws(()=>buildTeacherRecovery(exam,{...student,teacherId:'other'},session,false,now));
assert.throws(()=>buildTeacherRecovery(exam,student,{...session,status:'submitted'},false,now));
assert.throws(()=>buildTeacherRecovery(exam,student,{...session,draftAnswers:undefined},false,now));
assert.throws(()=>buildTeacherRecovery(exam,student,session,false,now+40*60*1000));
const packet=await encryptTeacherRecovery(checkpoint);
const decoded=await readTeacherRecovery(packet.encrypted,packet.code,exam,'NGUYỄN VĂN AN','a',now);
assert.deepEqual(decoded,checkpoint);
await assert.rejects(readTeacherRecovery(packet.encrypted,packet.code,exam,'Nguyen Van An','a',now));
await assert.rejects(readTeacherRecovery(packet.encrypted,packet.code,exam,'Nguyễn Văn An','b',now));
await assert.rejects(readTeacherRecovery(packet.encrypted,'wrong',exam,'Nguyễn Văn An','a',now));
await assert.rejects(readTeacherRecovery(packet.encrypted,packet.code,exam,'Nguyễn Văn An','a',now+11*60*1000));
console.log('Teacher recovery: encrypted checkpoint, exact name/class, old start time, same version, expiry and result guards passed.');
