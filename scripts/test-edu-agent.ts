import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { ECOSYSTEM_APPLICATIONS } from '../src/ecosystem';
import { AGENT_APP_IDS, AGENT_PROFILES, AGENT_ROLES, agentAppName, buildAgentPlan, isAgentAppId, resolveAgentContext } from '../src/lib/eduAgentCore';
assert.equal(Object.keys(AGENT_ROLES).length, 6);
assert.equal(AGENT_APP_IDS.length, 15);
assert.equal(new Set(AGENT_APP_IDS).size, 15);
for (const id of AGENT_APP_IDS) {
  assert.ok(AGENT_PROFILES[id].example);
  assert.ok(AGENT_PROFILES[id].steps.length >= 3);
  assert.ok(AGENT_PROFILES[id].related.every(isAgentAppId));
  assert.ok(agentAppName(id));
}
assert.ok(ECOSYSTEM_APPLICATIONS.every(app => isAgentAppId(app.id)));
assert.equal(resolveAgentContext('create-exam'), 'exam-manager');
assert.equal(resolveAgentContext('admin'), 'administration');
assert.equal(isAgentAppId('https://example.com'), false);
const plan = buildAgentPlan('Tạo đề thi, xếp thời khóa biểu và gộp Excel', 'desktop', 'coordinator');
assert.ok(plan.targets.includes('exam-manager'));
assert.ok(plan.targets.includes('smart-timetable'));
assert.ok(plan.targets.includes('excel-merger'));
assert.equal(plan.source, 'local');
assert.ok(plan.targets.every(isAgentAppId));
const read = (path: string) => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const app = read('src/App.tsx');
assert.ok(app.includes("!['landing','auth','admin','student_exam'].includes(currentView)"));
assert.ok(app.includes('currentUser && auth.currentUser'));
const dock = read('src/components/EduAgentDock.tsx');
assert.ok(dock.includes("await import('../lib/eduAgentCloud')"));
assert.ok(dock.includes('onTimetableCommand(request.trim().slice(0,500))'));
const cloud = read('src/lib/eduAgentCloud.ts');
assert.ok(cloud.includes('auth.currentUser?.uid !== uid'));
assert.ok(cloud.includes('model.generateContent(clean)'));
assert.ok(!/setDoc\(|updateDoc\(|deleteDoc\(/.test(cloud));
const timetable = read('src/components/SmartTimetable.tsx');
assert.ok(timetable.includes("navigatePage('agent')"));
assert.ok(timetable.includes('initialCommand={agentHandoff.command}'));
assert.ok(timetable.includes('!trialMode && agentUid'));
console.log('Edu AI agent profiles, routing, permission boundaries and timetable handoff checks passed.');
